"""Summary.

Write result tables to a Markdown file (reports/summary.md) so every number quoted in the README
comes from a script run, not from hand typing. Developed in NB11.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd


def _fmt(x: object) -> str:
    if isinstance(x, (float, np.floating)):
        if np.isnan(x):
            return ""
        if abs(x) >= 1e4:
            return f"{x / 1e6:,.2f}m"
        return f"{x:,.4f}" if abs(x) < 1 else f"{x:,.2f}"
    return str(x)


def _label(i: object) -> str:
    """Row label; MultiIndex tuples are joined with spaces."""
    if isinstance(i, tuple):
        return " ".join(str(x) for x in i if str(x))
    return str(i)


def markdown_table(df: pd.DataFrame) -> str:
    """Plain Markdown table (no extra dependencies). Large numbers shown in millions."""
    head = "| " + " | ".join([str(df.index.name or "")] + [str(c) for c in df.columns]) + " |"
    sep = "|" + "---|" * (len(df.columns) + 1)
    body = [
        "| " + " | ".join([_label(i)] + [_fmt(v) for v in row]) + " |"
        for i, row in zip(df.index, df.to_numpy(), strict=True)
    ]
    return "\n".join([head, sep, *body])


def write_summary(
    path: str | Path, tables: dict[str, pd.DataFrame], notes: list[str] | None = None
) -> None:
    lines = ["# Results summary", "", "Generated by scripts; do not edit by hand.", ""]
    for note in notes or []:
        lines.append(f"- {note}")
    for title, df in tables.items():
        lines += ["", f"## {title}", "", markdown_table(df)]
    Path(path).write_text("\n".join(lines) + "\n", encoding="utf-8")
